"""Bake the two printable-ASCII font atlases and their matching C++ metrics.

This development-only tool reads the installed DejaVu fonts at the paths below.
Running it overwrites both atlas PNGs and generated FontMetrics.h as one set; normal
builds and the game consume the committed outputs without Pillow or a font engine.

Each glyph records an ink rectangle, baseline bearings and proportional pen advance
in the original 64px font units. The renderer scales those values for text size and
normalizes atlas coordinates for sampling. Kerning, shaping and Unicode are outside
this small English-only UI pipeline. Font license notices live in assets/fonts/.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
font_root = Path('/usr/share/fonts/truetype/dejavu')
output = ['// Generated by tools/bake_fonts.py. DejaVu license: assets/fonts/LICENSE.',
          '#pragma once', '#include <array>', 'namespace woodland {',
          """/**
 * Describes one printable-ASCII glyph in a generated font atlas.
 *
 * x/y locate the bitmap rectangle's upper-left corner in atlas pixels; width/height
 * describe that rectangle, not a fixed character cell. left is the horizontal
 * bearing from the pen, and top is the distance above its baseline. BoardRenderer
 * places ink at (penX + left, baselineY - top), scaled from the baked 64px size.
 * It normalizes atlas pixel rectangles into UVs separately from screen placement.
 *
 * advance moves the pen to the next character, including spaces with no visible
 * ink. Text centering sums advances before drawing; this is proportional spacing,
 * not kerning or text shaping. serifGlyphs/sansGlyphs are indexed by ASCII code - 32
 * for codes 32..126. The renderer substitutes '?' for unsupported input bytes.
 * Regenerate numeric data and atlases together using tools/bake_fonts.py.
 */
struct FontGlyph { float x, y, width, height, left, top, advance; };"""]
for name, source in [('serif', 'DejaVuSerif.ttf'), ('sans', 'DejaVuSans.ttf')]:
    font = ImageFont.truetype(str(font_root / source), 64)
    atlas = Image.new('RGBA', (1280, 576))
    draw = ImageDraw.Draw(atlas)
    output.append(f'inline constexpr std::array<FontGlyph, 95> {name}Glyphs{{{{')
    for i, code in enumerate(range(32, 127)):
        char = chr(code)
        # Measure relative to the left baseline. Moving the ink into a padded atlas
        # cell must not discard its original bearings when it is later drawn as text.
        l, t, r, b = font.getbbox(char, anchor='ls')
        x, y = i % 16 * 80 + 4, i // 16 * 96 + 4
        # Padding isolates neighboring glyphs during filtered sampling. The advance
        # remains independent of ink width, so spaces and proportional letters align.
        draw.text((x - l, y - t), char, font=font, fill='white', anchor='ls')
        output.append(f'    {{{x}.f, {y}.f, {r-l}.f, {b-t}.f, {l}.f, {-t}.f, {font.getlength(char):.6f}f}},')
    output.append('}};')
    # Atlas pixels and metrics must be regenerated together; neither is a runtime
    # font parser. Do not hand-edit the generated header to adjust individual glyphs.
    atlas.save(root / 'assets/fonts' / f'{name}.png')
output.append('} // namespace woodland')
(root / 'src/rendering/FontMetrics.h').write_text('\n'.join(output) + '\n')
